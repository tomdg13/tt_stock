-- Oracle changes made for the ATM stock app
CREATE TABLE TT_PRODUCT_BARCODES (
  ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  PRODUCT_ID NUMBER NOT NULL,
  BARCODE VARCHAR2(100) NOT NULL,
  CREATED_AT DATE DEFAULT SYSDATE,
  CONSTRAINT UQ_PRODUCT_BARCODE UNIQUE (BARCODE)
);
ALTER TABLE TT_GOODS_RECEIPTS ADD (REF_NO VARCHAR2(100));
ALTER TABLE TT_STOCK_ISSUES ADD (REF_NO VARCHAR2(100));
CREATE TABLE TT_PURCHASE_ORDERS (
  ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  PO_NO VARCHAR2(100) NOT NULL,
  TITLE VARCHAR2(300),
  VENDOR VARCHAR2(200),
  NOTE VARCHAR2(1000),
  STATUS VARCHAR2(20) DEFAULT 'open',
  CREATED_BY NUMBER,
  CREATED_AT DATE DEFAULT SYSDATE,
  CONSTRAINT UQ_PO_NO UNIQUE (PO_NO)
);
CREATE TABLE TT_PO_DOCUMENTS (
  ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  PO_ID NUMBER NOT NULL REFERENCES TT_PURCHASE_ORDERS(ID),
  FILE_PATH VARCHAR2(300) NOT NULL,
  ORIG_NAME VARCHAR2(300),
  MIME VARCHAR2(100),
  SIZE_BYTES NUMBER,
  CREATED_AT DATE DEFAULT SYSDATE
);
